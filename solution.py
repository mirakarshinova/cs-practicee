import numpy as np


def make_hours() -> list[int]:
    """Создаёт список часов от 0 до 21 с шагом 3."""
    # np.arange(0, 22, 3) создаёт массив: 0, 3, 6, ..., 21.
    # Правая граница не включается, поэтому указываем 22, чтобы включить 21.
    # tolist() преобразует массив NumPy в обычный список Python.
    return np.arange(0, 22, 3).tolist()


def vector_report(values: list[float]) -> dict:
    """Возвращает словарь с выбранными элементами и срезами вектора."""
    # Преобразуем входной список в массив NumPy.
    # dtype=float задаёт вещественный тип элементов.
    arr = np.asarray(values, dtype=float)

    return {
        # Третий элемент: индекс 2, так как индексация начинается с нуля.
        "third": arr[2].item(),
        # Последний элемент: индекс -1.
        "last": arr[-1].item(),
        # Срез с индексами 2, 3, 4 и 5 (правая граница 6 не включается).
        "middle": arr[2:6].tolist(),
        # Каждый второй элемент, начиная с первого (индекс 0).
        "every_second": arr[::2].tolist(),
        # Все элементы в обратном порядке.
        "reversed": arr[::-1].tolist(),
    }


def change_vector(values: list[float]) -> list[float]:
    """Изменяет копию списка: сначала индексы 2–4, затем каждый второй элемент."""
    # Создаём независимую копию массива, чтобы не менять исходный список.
    arr = np.asarray(values, dtype=float).copy()

    # Заменяем элементы с индексами 2, 3 и 4 на 99.
    # Правая граница среза (5) не включается.
    arr[2:5] = 99

    # Заменяем каждый второй элемент, начиная с индекса 0, на -1.
    # Эта операция выполняется ПОСЛЕ предыдущей замены.
    arr[::2] = -1

    # Возвращаем результат как обычный список Python.
    return arr.tolist()


def cap_above(values: list[float], limit: float) -> list[float]:
    """Заменяет все значения больше limit на limit, не меняя исходный список."""
    # Работаем с копией, чтобы исходный список остался без изменений.
    arr = np.asarray(values, dtype=float).copy()

    # Логическая маска arr > limit выбирает только элементы,
    # которые строго больше заданного ограничения.
    # Все выбранные элементы заменяем на limit.
    arr[arr > limit] = limit

    return arr.tolist()


def celsius_to_fahrenheit(values: list[float]) -> list[float]:
    """Переводит все температуры из градусов Цельсия в градусы Фаренгейта."""
    # Преобразуем список в массив NumPy, чтобы применить формулу сразу ко всему вектору.
    arr = np.asarray(values, dtype=float)

    # Формула перевода: F = C * 9 / 5 + 32.
    # Broadcasting позволяет выполнить вычисление над каждым элементом без цикла.
    return (arr * 9 / 5 + 32).tolist()
